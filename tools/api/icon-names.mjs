const icons = JSON.parse(readFileSync("icons.json", "utf8"));
const out = {};
for (const [i, name] of Object.entries(names)) {
  if (out[name]) throw new Error("duplicate " + name);
  out[name] = icons[i].svg.replace(/'/g, '"');
}
const lines = Object.entries(out).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const file = `/* SpotiKit icons */
(function (SpotiKit) {
  "use strict";
  var internal = SpotiKit && SpotiKit._internal;
  if (!internal) {
    return;
  }

  var markup = Object.freeze({
${lines.join("\n")}
  });

  function size(value) {
    return value === undefined ? 16 : value;
  }

  SpotiKit.Icons = Object.freeze({
    names: Object.freeze(Object.keys(markup)),
    has: function (name) {
      return Object.prototype.hasOwnProperty.call(markup, name);
    },
    markup: function (name) {
      return markup[name];
    },
    svg: function (name, px) {
      if (!markup[name]) {
        return "";
      }
      var s = size(px);
      return '<svg role="img" aria-hidden="true" width="' + s + '" height="' + s + '" viewBox="0 0 16 16" fill="currentColor">' + markup[name] + "</svg>";
    },
    element: function (name, props) {
      var React = SpotiKit.React;
      var s = size(props && props.size);
      return React.createElement("svg", Object.assign({
        role: "img", "aria-hidden": "true", width: s, height: s, viewBox: "0 0 16 16", fill: "currentColor",
        dangerouslySetInnerHTML: { __html: markup[name] || "" },
      }, props, { size: undefined }));
    },
  });
})(window.SpotiKit);
`;
writeFileSync(process.argv[2], file);
